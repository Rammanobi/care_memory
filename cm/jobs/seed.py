"""Lane B: deterministic, idempotent seed (seed 42) with the SAME sample content the UI shows.

    python -m cm.jobs.seed            # load (safe to repeat; no duplicates)
    python -m cm.jobs.seed --reset    # wipe cm tables first
    python -m cm.jobs.seed --small    # 6 patients only

All data is fictional: phones 9000000xxx, emails @example.test. Content comes from seed_data.json (a dump
of web/src/mocks/seed.ts makeSeed()) plus the patient-app sample in seed_patient_app.py.
Demo passwords come from DEMO_USER_PASSWORDS in .env (generated there on first run, never printed).
"""

from __future__ import annotations

import argparse
import json
import secrets
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import Any
from uuid import UUID

from cm.api.auth import hash_password
from cm.core import clock
from cm.core.config import REPO_ROOT, load_dotenv, load_settings
from cm.core.db import close_pool, connect_direct
from cm.core.ids import det_id
from cm.jobs import migrate

DATA = Path(__file__).with_name("seed_data.json")
DAY0 = date(2026, 8, 27)
DEFAULT_SIM_DAY = 59
SMALL_CODES = {"PT-0142", "PT-0087", "PT-0213", "PT-0176", "PT-0900", "PT-0901"}
USERS = {  # username -> (token, role, display name)
    "dr.rao": ("D-01", "doctor", "Dr. A. Rao"),
    "admin.demo": ("A-01", "admin", "Demo Admin"),
    "ravi.pt0142": ("P-0142", "patient", "Ravi"),
    "lakshmi.s01": ("S-01", "supporter", "Lakshmi"),
}
CLINIC_CODES = {"anantapur": "AP-ANT-01", "kalyandurg": "AP-KLD-01", "dharmavaram": "AP-DHM-01"}
BLOCK_OF = {"anantapur": "Block A", "kalyandurg": "Block B", "dharmavaram": "Block C"}


@dataclass
class Ctx:
    conn: Any
    state: dict[str, Any]
    small: bool
    sim_now: datetime
    today: date
    clinic_ids: dict[str, UUID] = field(default_factory=dict)
    patients: dict[str, dict[str, Any]] = field(default_factory=dict)  # code -> ids/start/clinic
    doctor_id: UUID | None = None
    counts: dict[str, int] = field(default_factory=dict)

    def keep(self, code: str) -> bool:
        return not self.small or code in SMALL_CODES

    def bump(self, key: str, n: int = 1) -> None:
        self.counts[key] = self.counts.get(key, 0) + n


def demo_passwords() -> dict[str, str]:
    """Read DEMO_USER_PASSWORDS from the environment/.env; generate and store in .env when absent."""
    import os

    load_dotenv()
    raw = os.environ.get("DEMO_USER_PASSWORDS")
    if raw:
        return json.loads(raw)
    pw = {u: secrets.token_urlsafe(12) for u in USERS}
    env = REPO_ROOT / ".env"
    with env.open("a", encoding="utf-8") as f:
        f.write(f"\nDEMO_USER_PASSWORDS='{json.dumps(pw)}'\n")
    os.environ["DEMO_USER_PASSWORDS"] = json.dumps(pw)
    _note_env_example()
    return pw


def _note_env_example() -> None:
    ex = REPO_ROOT / ".env.example"
    text = ex.read_text(encoding="utf-8")
    marker = "# DEMO_USER_PASSWORDS users:"
    if marker not in text:
        ex.write_text(
            text.rstrip("\n") + f"\n\n{marker} {', '.join(USERS)} (test passwords are generated by "
            "`python -m cm.jobs.seed` into your git-ignored .env; placeholder only: <generated-in-.env>)\n",
            encoding="utf-8",
        )


def reset_tables(conn: Any) -> None:
    conn.execute(
        "TRUNCATE cm.districts, cm.persons, cm.task_runs, cm.audit_log, cm.settings, cm.templates, "
        "cm.sim_clock, cm.sim_inbox, cm.eval_runs, cm.mock_nikshay_patients, cm.mock_nikshay_payments, "
        "cm.gmail_state RESTART IDENTITY CASCADE"
    )


def seed_org(ctx: Ctx) -> None:
    c = ctx.conn
    did = det_id("district", "anantapur")
    c.execute(
        "INSERT INTO cm.districts (district_id, name) VALUES (%s,'Anantapur District') ON CONFLICT DO NOTHING",
        (did,),
    )
    for slug, block in BLOCK_OF.items():
        bid = det_id("block", block)
        c.execute(
            "INSERT INTO cm.blocks (block_id, district_id, name) VALUES (%s,%s,%s) ON CONFLICT DO NOTHING",
            (bid, did, block),
        )
        info = next(x for x in ctx.state["clinics"] if x["id"] == slug)
        cid = det_id("clinic", slug)
        ctx.clinic_ids[slug] = cid
        c.execute(
            "INSERT INTO cm.clinics (clinic_id, block_id, name, facility_code) VALUES (%s,%s,%s,%s) ON CONFLICT DO NOTHING",
            (cid, bid, info["name"], CLINIC_CODES[slug]),
        )
    c.execute(
        "INSERT INTO cm.sim_clock (run_id, seed, sim_day, day0_date, max_computed_day, status) "
        "SELECT %s, 42, %s, %s, %s, 'ready' WHERE NOT EXISTS (SELECT 1 FROM cm.sim_clock WHERE active)",
        (det_id("simclock"), DEFAULT_SIM_DAY, DAY0, DEFAULT_SIM_DAY),
    )


def _person(
    ctx: Ctx, token: str, role: str, clinic: str | None, name: str | None, idx: int
) -> UUID:
    pid = det_id("person", token)
    cid = ctx.clinic_ids.get(clinic) if clinic else None
    did = det_id("district", "anantapur") if role in ("doctor", "admin") else None
    ctx.conn.execute(
        "INSERT INTO cm.persons (person_id, role, token, clinic_id, district_id) VALUES (%s,%s,%s,%s,%s) "
        "ON CONFLICT DO NOTHING",
        (pid, role, token, cid, did),
    )
    phone, email = f"9000000{idx:03d}", f"{token.lower()}@example.test"
    ctx.conn.execute(
        "INSERT INTO cm.identity_vault (person_id, enc_name, enc_phone, enc_email) VALUES (%s,%s,%s,%s) "
        "ON CONFLICT DO NOTHING",
        (pid, name.encode() if name else None, phone.encode(), email.encode()),
    )
    return pid


def seed_people(ctx: Ctx) -> None:
    ctx.doctor_id = _person(ctx, "D-01", "doctor", "anantapur", "Dr. A. Rao", 1)
    _person(ctx, "A-01", "admin", None, "Demo Admin", 2)
    sup_n = 1
    for i, row in enumerate(ctx.state["patients"]):
        code = row["code"]
        if not ctx.keep(code):
            continue
        token = "P-" + code.split("-")[1]
        name = "Ravi" if code == "PT-0142" else None
        pid = _person(ctx, token, "patient", row["clinic"], name, 100 + i)
        start = ctx.today - timedelta(days=row["day"] - 1)
        patient_id = det_id("patient", code)
        ctx.conn.execute(
            "INSERT INTO cm.patients (patient_id, person_id, clinic_id, treatment_start, regimen, phase, nikshay_id) "
            "VALUES (%s,%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING",
            (
                patient_id,
                pid,
                ctx.clinic_ids[row["clinic"]],
                start,
                "Standard six-month course",
                "intensive" if row["day"] <= 56 else "continuation",
                f"NK-{code.split('-')[1]}",
            ),
        )
        ctx.patients[code] = {
            "patient_id": patient_id,
            "person_id": pid,
            "start": start,
            "row": row,
            "token": token,
        }
        if row["supporter"] == "Linked":
            tok = "S-01" if code == "PT-0142" else f"S-{sup_n + 1:02d}"
            sup_id = _person(
                ctx,
                tok,
                "supporter",
                row["clinic"],
                "Lakshmi" if code == "PT-0142" else None,
                300 + int(tok[2:]),
            )
            sup_n += code != "PT-0142"
            ctx.patients[code]["supporter_id"] = sup_id
            ctx.conn.execute(
                "INSERT INTO cm.support_assignments (patient_id, supporter_id, from_date) VALUES (%s,%s,%s) "
                "ON CONFLICT DO NOTHING",
                (patient_id, sup_id, start),
            )
    ctx.bump("patients", len(ctx.patients))


def seed_credentials(ctx: Ctx) -> None:
    pw = demo_passwords()
    for username, (token, _role, _name) in USERS.items():
        if token == "P-0142" and "PT-0142" not in ctx.patients:  # noqa: S105
            continue
        person_id = det_id("person", token)
        if ctx.conn.execute(
            "SELECT 1 FROM cm.auth_credentials WHERE person_id=%s", (person_id,)
        ).fetchone():
            continue
        ctx.conn.execute(
            "INSERT INTO cm.auth_credentials (person_id, username, password_hash) VALUES (%s,%s,%s)",
            (person_id, username, hash_password(pw[username])),
        )


def run_seed(
    seed: int = 42, small: bool = False, reset: bool = False, sim_day: int = DEFAULT_SIM_DAY
) -> dict[str, int]:
    """Load the sample data. Returns row counts written/ensured in this run."""
    from cm.jobs import seed_events, seed_ops, seed_review

    migrate.run_migrations()
    state = json.loads(DATA.read_text(encoding="utf-8"))
    sim_now = clock.sim_instant(DAY0, sim_day)
    with connect_direct() as conn:
        if reset:
            reset_tables(conn)
        ctx = Ctx(conn, state, small, sim_now, sim_now.astimezone(clock.IST).date())
        clock.pin(sim_now)
        seed_org(ctx)
        seed_people(ctx)
        seed_credentials(ctx)
        seed_events.seed_consents_and_events(ctx)
        seed_review.seed_review(ctx)
        seed_ops.seed_ops(ctx, seed)
        conn.commit()
    close_pool()
    return ctx.counts


def main() -> None:
    ap = argparse.ArgumentParser(description="Seed CareMemory with the deterministic sample data")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--reset", action="store_true")
    ap.add_argument("--small", action="store_true")
    ap.add_argument("--sim-day", type=int, default=DEFAULT_SIM_DAY)
    ap.add_argument("--patients", type=int, default=20, help="accepted for Makefile compatibility")
    ap.add_argument("--days", type=int, default=60, help="accepted for Makefile compatibility")
    ap.add_argument("--backfill", action="store_true", help="accepted for Makefile compatibility")
    a = ap.parse_args()
    load_settings.cache_clear()
    counts = run_seed(a.seed, a.small, a.reset, a.sim_day)
    print("seed done:", ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))


if __name__ == "__main__":
    main()
